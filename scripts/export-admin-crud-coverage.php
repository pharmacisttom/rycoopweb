<?php
declare(strict_types=1);

/**
 * Heuristic CRUD coverage audit for registered Admin API routes.
 * CLI, no dispatch, no database access. Intended to identify modules needing
 * human review, not to certify implementation correctness.
 */
require dirname(__DIR__) . '/vendor/autoload.php';

$router = new \App\Core\Router();
require dirname(__DIR__) . '/config/routes.php';
$routes = (new ReflectionProperty(\App\Core\Router::class, 'routes'))->getValue($router);

$modules = [];
foreach ($routes as $route) {
    $path = $route['path'];
    if (!str_starts_with($path, '/api/admin/')) continue;
    $tail = substr($path, strlen('/api/admin/'));
    $module = explode('/', $tail)[0] ?: '(root)';
    $method = $route['method'];
    $handler = is_string($route['handler']) ? $route['handler'] : '';
    $last = strtolower((string)substr($tail, strrpos($tail, '/') + 1));
    $action = strtolower((string)substr($handler, strrpos($handler, '@') + 1));
    $isItem = preg_match('~\{(?:id|uuid|slug|member|user|photo|album)\}~', $tail) === 1;
    $kind = 'workflow';
    if ($method === 'GET') $kind = $isItem ? 'read_one' : 'read_list';
    elseif (preg_match('/(?:delete|destroy|remove|archive|disable)/', $action.' '.$last)) $kind = 'delete';
    elseif (preg_match('/(?:update|edit|change|reorder|caption|cover)/', $action.' '.$last)) $kind = 'update';
    elseif (preg_match('/(?:create|store|upload|submit|add)/', $action.' '.$last)) $kind = 'create';
    elseif ($method === 'POST' && !$isItem) $kind = 'create';
    elseif (in_array($method, ['PUT','PATCH'], true)) $kind = 'update';
    elseif ($method === 'DELETE') $kind = 'delete';
    $modules[$module]['routes'][] = [$method, $path, $handler, $kind];
    $modules[$module][$kind] = true;
}
ksort($modules);
$filename = dirname(__DIR__) . '/docs/audit/ADMIN_CRUD_COVERAGE_MATRIX.md';
$lines = [
    '# RYCOOPWEB — Admin API CRUD Coverage Matrix',
    '',
    'Generated by `scripts/export-admin-crud-coverage.php` from registered routes. No DB connections or requests.',
    '',
    '**Interpretation:** Route-name heuristics only. A missing category is a review priority, not necessarily a defect.',
    'A present category does **not** prove persistence, permissions, audit logs or a working React UI.',
    '',
    '| Module | Listed API Routes | List | Detail | Create | Update | Delete/Disable |',
    '|---|---:|---|---|---|---|---|',
];
$gaps = [];
$total = 0;
foreach ($modules as $module => $data) {
    $count = count($data['routes']);
    $total += $count;
    $checks = [];
    foreach (['read_list','read_one','create','update','delete'] as $kind) {
        $checks[] = !empty($data[$kind]) ? 'yes' : '—';
    }
    $lines[] = '| `' . $module . '` | ' . $count . ' | ' . implode(' | ', $checks) . ' |';
    if (count(array_filter($checks, static fn($v) => $v === '—')) > 0) $gaps[] = $module;
}
$lines[] = '';
$lines[] = sprintf('Total: %d registered Admin API routes across %d top-level modules.', $total, count($modules));
$lines[] = '';
$lines[] = '## Modules requiring a CRUD completeness decision';
$lines[] = '';
$lines[] = $gaps ? implode(', ', array_map(static fn($m) => '`'.$m.'`', $gaps)) : 'No heuristic gaps';
$lines[] = '';
$lines[] = 'Read-only dashboards, authentication and approvals are not expected to implement all five CRUD operations.';
$lines[] = '';
$lines[] = '## Endpoint inventory';
$lines[] = '';
$lines[] = '| Method | Path | Handler | Inferred operation |';
$lines[] = '|---|---|---|---|';
foreach ($modules as $data) foreach ($data['routes'] as [$method,$path,$handler,$kind]) {
    $lines[] = "| $method | `$path` | `$handler` | $kind |";
}
file_put_contents($filename, implode("\n", $lines) . "\n");
printf("PASS: %d API routes, %d modules, %d heuristic review groups\n", $total, count($modules), count($gaps));
echo "Output: docs/audit/ADMIN_CRUD_COVERAGE_MATRIX.md\n";
